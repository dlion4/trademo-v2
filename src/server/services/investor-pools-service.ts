/** Weighted realized return across every completed cycle in the fixture. */
export const reachedRoiTotal = (rows: CompletedPool[]) =>
  reachedRoi(
    rows.reduce((sum, row) => sum + row.netEarnings, 0),
    rows.reduce((sum, row) => sum + row.investment, 0),
  );
