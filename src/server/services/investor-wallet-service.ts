export function getWalletWorkspace(): WalletWorkspace {
  const investments = getInvestmentsWorkspace();
  const transactions = withRunningBalance(LEDGER, OPENING_BALANCE);
  const ledgerPayouts = payouts();
  const available = transactions[transactions.length - 1].balanceAfter;
  const lockedInPools = investments.summary.activeCapital;
  const pending = ledgerPayouts.filter((row) => row.status === "processing");

  const balance: WalletWorkspace["balance"] = {
    available,
    lockedInPools,
    bookedInPools: investments.summary.bookedCapital,
    interestRegistered: investments.summary.interestCapital,
    accruedInPools: investments.active.reduce(
      (sum: number, row) => sum + row.netEarned,
      0,
    ),
    pendingPayoutGross: pending.reduce((sum, row) => sum + row.gross, 0),
    pendingPayoutNet: pending.reduce((sum, row) => sum + row.net, 0),
    pendingPayoutCount: pending.length,
    totalAccountValue: available + lockedInPools,
    currency: "USD",
    openingBalance: OPENING_BALANCE,
    statementFrom: STATEMENT_FROM,
    statementTo: WALLET_AS_OF,
  };

  const lifetime: WalletWorkspace["lifetime"] = {
    ...deriveLifetime(transactions),
    accruedInPools: balance.accruedInPools,
  };

  return {
    mode: "demo",
    asOf: WALLET_AS_OF,
    revision: 0,
    profile: {
      id: investments.profile.id,
      displayName: investments.profile.displayName,
      email: "jane.investor@example.com",
      investorSince: investments.profile.investorSince,
      kycLevel: investments.profile.kycLevel,
      kycVerifiedAt: investments.profile.kycVerifiedAt,
      country: investments.profile.country,
      currency: investments.profile.currency,
      tier: investments.profile.tier,
      unread: investments.profile.unread,
      monthRoiPct: investments.profile.monthRoiPct,
    },
    balance,
    lifetime,
    depositRails: DEPOSIT_RAILS,
    payoutRails: PAYOUT_RAILS,
    methods: METHODS,
    payouts: ledgerPayouts,
    transactions,
    limits: limits(
      balance,
      lifetime,
      depositedToday(transactions, WALLET_AS_OF),
    ),
    filters: { types: [], methods: [], from: "", to: "", query: "" },
    preferences: {
      emailReceipts: true,
      autoPayout: false,
      payoutThreshold: 500,
      lowBalanceAlert: true,
    },
    exports: [],
    acknowledgements: [],
    support: [],
    audit: [],
  };
}
